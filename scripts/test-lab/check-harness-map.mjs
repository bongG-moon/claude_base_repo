// Owned-app QA. Isolated registration + synthetic CLI, no real model/account.
import fs from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {createRequire} from 'node:module';
const args=Object.fromEntries(process.argv.slice(2).reduce((xs,x,i,a)=>{if(x.startsWith('--'))xs.push([x.slice(2),a[i+1]]);return xs;},[]));
if(!args.modules||!args.runtime)throw new Error('--modules and --runtime required');
const runtime=JSON.parse(await fs.readFile(args.runtime,'utf8'));
const req=createRequire(path.join(path.resolve(args.modules),'_map_qa.cjs'));
const {chromium}=req('playwright');
const browser=await chromium.launch({channel:'msedge',headless:true});
const errors=[],external=[];
const out=path.join(runtime.output,'map-screenshots');await fs.mkdir(out,{recursive:true});
try{
  const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(/^https?:/.test(r.url())&&!r.url().startsWith(new URL(runtime.url).origin))external.push(r.url());});
  await page.goto(runtime.url);
  await page.locator('#choose-folder').click();
  await page.locator('#folder-input').fill(runtime.workspace);
  await page.locator('#trust').check();
  await page.locator('#confirm-folder').click();
  await page.locator('#folder-dialog').waitFor({state:'hidden'});
  await page.locator('#learn-open').click();
  await page.getByRole('button',{name:'이 폴더의 하네스 구성 한눈에 보기',exact:true}).click();
  const frame=page.frameLocator('.harness-map-frame');
  await frame.getByRole('heading',{name:'이 폴더에는 무엇이 적용될까요?',exact:true}).waitFor();
  await page.locator('#companion-message').filter({hasText:/^$/}).waitFor({state:'attached'});
  if(await page.locator('.harness-map-frame').getAttribute('sandbox')!=='')throw new Error('map must be sandboxed');
  if(await frame.locator('script').count())throw new Error('map must not contain scripts');
  for(const label of ['회사 공통','개인 전체','이 프로젝트'])await frame.getByRole('heading',{name:label,exact:true}).waitFor();
  const company=frame.locator('#company');
  await company.locator('.category>summary').filter({hasText:'스킬'}).click();
  await company.getByText('company-agent:html-report',{exact:true}).waitFor();
  await company.getByText('company-agent:html-report',{exact:true}).locator('..').locator('..').getByText('위치 보기',{exact:true}).click();
  if(!(await company.innerText()).includes('SKILL.md'))throw new Error('source path missing');
  const snapshot=await page.locator('.harness-map-frame').getAttribute('srcdoc');
  if(snapshot.includes('fixture-key')||snapshot.includes('NEVER_EXPORT'))throw new Error('secret included in map');
  if(await frame.locator('.areas').evaluate(n=>getComputedStyle(n).gridTemplateColumns.split(' ').length)!==3)throw new Error('wide embedded map must show three columns');
  await frame.locator('body').evaluate(()=>scrollTo(0,0));
  await page.locator('#companion-dialog').evaluate(n=>n.scrollTop=0);
  await page.screenshot({path:path.join(out,'workspace-map-1440.png')});
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'구성 지도 HTML 저장',exact:true}).click();
  const download=await downloadPromise;
  const saved=path.join(runtime.output,'downloaded-harness-map.html');await download.saveAs(saved);
  if((await fs.readFile(saved,'utf8'))!==snapshot)throw new Error('export differs from displayed snapshot');
  await page.locator('#companion-tabs').getByRole('button',{name:'새로고침',exact:true}).click();
  await page.locator('#companion-message').filter({hasText:/^$/}).waitFor({state:'attached'});
  await frame.getByRole('heading',{name:'이 폴더에는 무엇이 적용될까요?',exact:true}).waitFor();
  await page.setViewportSize({width:390,height:844});
  await frame.locator('body').evaluate(()=>scrollTo(0,0));
  await page.locator('#companion-dialog').evaluate(n=>n.scrollTop=0);
  if(await page.locator('body').evaluate(n=>n.scrollWidth>innerWidth+1))throw new Error('workspace mobile horizontal overflow');
  if(await frame.locator('body').evaluate(n=>n.scrollWidth>innerWidth+1))throw new Error('embedded map mobile horizontal overflow');
  await page.screenshot({path:path.join(out,'workspace-map-390.png')});
  if(await page.locator('.message').count())throw new Error('map sent a model request');
  const standalone=await browser.newPage({viewport:{width:1440,height:1050}});
  standalone.on('request',r=>{if(/^https?:/.test(r.url()))external.push(r.url());});
  await standalone.goto(pathToFileURL(saved).href);
  await standalone.getByRole('heading',{name:'이 폴더에는 무엇이 적용될까요?',exact:true}).waitFor();
  const columns=await standalone.locator('.areas').evaluate(n=>getComputedStyle(n).gridTemplateColumns.split(' ').length);
  if(columns!==3)throw new Error('wide standalone map must have three columns');
  await standalone.screenshot({path:path.join(out,'standalone-map-1440.png'),fullPage:true});
  await standalone.setViewportSize({width:390,height:844});
  if(await standalone.locator('body').evaluate(n=>n.scrollWidth>innerWidth+1))throw new Error('standalone mobile overflow');
  await standalone.screenshot({path:path.join(out,'standalone-map-390.png'),fullPage:true});
  if(args.current){
    await standalone.setViewportSize({width:1440,height:1050});
    await standalone.goto(pathToFileURL(path.resolve(args.current)).href);
    await standalone.screenshot({path:path.join(out,'current-directory-map.png'),fullPage:true});
  }
  if(errors.length||external.length)throw new Error(JSON.stringify({errors,external}));
  const summary={ok:true,threeScopes:true,sandbox:true,downloadMatches:true,mobile:true,modelRequests:0,externalRequests:0,errors};
  await fs.writeFile(path.join(runtime.output,'map-browser-result.json'),JSON.stringify(summary,null,2));
  process.stdout.write(JSON.stringify(summary)+'\n');
}finally{await browser.close();}
